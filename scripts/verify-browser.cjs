async (page) => {
  const results=[];
  const check=(ok,label)=>{if(!ok)throw new Error(label);results.push(label);};
  await page.goto('http://127.0.0.1:4173');
  await page.bringToFront();
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'暂停漂流',exact:true}).click();
  const file=page.getByRole('button',{name:'旅行清单.txt',exact:true});
  if((await file.getAttribute('class')).includes('at-sea'))await file.press('s');
  await page.waitForTimeout(500);
  const box=await file.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();await page.mouse.move(700,430,{steps:28});await page.mouse.up();
  check((await file.getAttribute('class')).includes('at-sea'),'Dragging a shore file transforms it into a boat');
  await page.getByRole('button',{name:'找文件',exact:true}).click();
  await page.getByRole('searchbox',{name:'搜索文件'}).fill('旅行');
  const result=page.locator('#search-results button');
  check(await result.count()===1,'Search filters to the matching file');
  await result.click();
  check((await file.getAttribute('class')).includes('found'),'Search locates and highlights the boat');
  await file.press('Enter');
  await page.waitForFunction(()=>document.querySelector('#preview-content').textContent.includes('下一次去海边'));
  check((await page.locator('#preview-content').innerText()).includes('下一次去海边'),'Keyboard opening displays the original text');
  await page.getByRole('button',{name:'关闭预览'}).click();
  await page.locator('#file-input').setInputFiles({name:'验证文件.txt',mimeType:'text/plain',buffer:Buffer.from('真实文件导入测试\n<svg onload=alert(1)>只显示文字，不执行。','utf8')});
  await page.getByRole('button',{name:'验证文件.txt',exact:true}).waitFor();
  await page.waitForTimeout(350);
  await page.reload();
  const imported=page.getByRole('button',{name:'验证文件.txt',exact:true});
  await imported.waitFor();
  check(await imported.count()===1,'Imported file persists after reload');
  await imported.press('Enter');
  await page.waitForFunction(()=>document.querySelector('#preview-content').textContent.includes('真实文件导入测试'));
  check((await page.locator('#preview-content').innerText()).includes('<svg onload=alert(1)>'),'Imported text previews safely as text');
  check(await page.locator('#preview-content svg').count()===0,'Imported markup is never executed');
  await page.getByRole('button',{name:'移出海岛',exact:true}).click();
  await imported.waitFor({state:'detached'});
  check(await page.getByRole('button',{name:'验证文件.txt',exact:true}).count()===0,'Removing a file removes only its island entry');
  await page.getByRole('button',{name:'全部靠岸',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.file.at-sea').length===0);
  check(true,'All boats return to shore');
  await page.getByRole('button',{name:'海边的一天.webp',exact:true}).press('Enter');
  await page.locator('#preview-content img').waitFor();
  await page.waitForFunction(()=>document.querySelector('#preview-content img')?.naturalWidth>0);
  check(await page.locator('#preview-content img').evaluate(el=>el.complete&&el.naturalWidth>0),'Image preview loads');
  await page.getByRole('button',{name:'关闭预览'}).click();
  await page.emulateMedia({reducedMotion:'reduce'});
  const photo=page.getByRole('button',{name:'海边的一天.webp',exact:true});
  await photo.press('s');
  await page.waitForTimeout(100);
  const before=await photo.getAttribute('style');await page.waitForTimeout(300);
  check(before===await photo.getAttribute('style'),'Reduced-motion preference stops automatic boat movement');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  check(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'Mobile viewport has no horizontal overflow');
  const dock=await page.locator('.dock').boundingBox();check(dock.x>=0&&dock.x+dock.width<=390,'All toolbar controls fit mobile width');
  await page.screenshot({path:'output/playwright/mobile-check.png'});
  await page.evaluate(results=>document.documentElement.dataset.verification=JSON.stringify(results),results);
  return results;
}
